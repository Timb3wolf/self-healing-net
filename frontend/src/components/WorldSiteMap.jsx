const SITES = [
  { id: 'london', name: 'London, UK', lat: 51.5, lon: -0.1, nodes: 6, ip: '10.0.0.1' },
  { id: 'frankfurt', name: 'Frankfurt, DE', lat: 50.1, lon: 8.7, nodes: 5, ip: '10.0.1.1' },
  { id: 'newyork', name: 'New York, US', lat: 40.7, lon: -74.0, nodes: 7, ip: '10.0.2.1' },
  { id: 'chennai', name: 'Chennai, IN', lat: 13.1, lon: 80.3, nodes: 6, ip: '10.0.3.1' },
  { id: 'singapore', name: 'Singapore, SG', lat: 1.35, lon: 103.8, nodes: 5, ip: '10.0.4.1' },
];

export default function WorldSiteMap({
  isAnomalous = false,
  anomalousTarget = 'A-B',
  onSelectSite = null,
}) {
  const [hoveredSite, setHoveredSite] = useState(null);

  // Generate continent land dots
  const landDots = [];
  MASK.forEach((row, r) => {
    for (let c = 0; c < row.length; c++) {
      if (row[c] === '1') {
        landDots.push({ cx: c * 3 + 1.5, cy: r * 3 + 1.5 });
      }
    }
  });

  const xy = (s) => ({ x: s.lon + 180, y: 84 - s.lat });

  const ARCS = [
    ['london', 'newyork'],
    ['london', 'frankfurt'],
    ['frankfurt', 'chennai'],
    ['chennai', 'singapore'],
    ['london', 'chennai'],
  ];

  return (
    <div className="glass-panel" style={{ padding: '1.25rem', position: 'relative' }}>
      <div className="card-header" style={{ padding: '0 0 0.75rem 0', marginBottom: '0.75rem' }}>
        <div className="card-title-group">
          <Globe size={18} color="#22C3E6" />
          <span className="card-title">Simulated 5G Global Sites</span>
        </div>
        <span style={{ fontSize: '0.72rem', color: '#8597AE', fontFamily: 'JetBrains Mono' }}>
          Click a PoP to inspect site telemetry
        </span>
      </div>

      <div style={{ position: 'relative', width: '100%' }}>
        <svg id="worldmap" viewBox="0 0 360 141" style={{ width: '100%', height: 'auto', display: 'block' }}>
          {/* Continent Land Dots */}
          <g fill="#1B2B42">
            {landDots.map((d, i) => (
              <circle key={i} cx={d.cx} cy={d.cy} r={0.95} />
            ))}
          </g>

          {/* Connecting Arcs */}
          {ARCS.map(([srcId, dstId], i) => {
            const s1 = SITES.find((s) => s.id === srcId);
            const s2 = SITES.find((s) => s.id === dstId);
            if (!s1 || !s2) return null;
            const A = xy(s1);
            const B = xy(s2);
            const mx = (A.x + B.x) / 2;
            const my = Math.min(A.y, B.y) - 12;
            const isArcAffected = isAnomalous && (srcId === 'frankfurt' || dstId === 'frankfurt');

            return (
              <path
                key={i}
                d={`M${A.x},${A.y} Q${mx},${my} ${B.x},${B.y}`}
                fill="none"
                stroke={isArcAffected ? '#F05A5A' : '#22C3E6'}
                strokeWidth={0.5}
                strokeDasharray="2 2"
                opacity={0.65}
              />
            );
          })}

          {/* Site Pins */}
          {SITES.map((site) => {
            const pos = xy(site);
            const isSiteDegraded = isAnomalous && (site.id === 'frankfurt' || site.id === 'newyork');
            const color = isSiteDegraded ? '#F05A5A' : '#2ECC8F';

            return (
              <g
                key={site.id}
                className="site-dot"
                style={{ cursor: 'pointer' }}
                onClick={() => onSelectSite && onSelectSite(site.id)}
                onMouseEnter={() => setHoveredSite(site)}
                onMouseLeave={() => setHoveredSite(null)}
              >
                {/* Invisible hit target */}
                <circle cx={pos.x} cy={pos.y} r={7} fill="transparent" />
                {/* Animated Pulsing Ring */}
                <circle
                  className="ring"
                  cx={pos.x}
                  cy={pos.y}
                  r={3}
                  stroke={color}
                  fill="none"
                  strokeWidth={0.8}
                />
                {/* Core Dot */}
                <circle cx={pos.x} cy={pos.y} r={2.2} fill={color} />
                {/* Site Label */}
                <text
                  x={pos.x}
                  y={pos.y - 4.5}
                  fontSize={4.2}
                  fill="#DCE6F2"
                  textAnchor="middle"
                  fontFamily="Barlow, sans-serif"
                  fontWeight={600}
                >
                  {site.name.split(',')[0]}
                </text>
              </g>
            );
          })}
        </svg>

        {/* Hovercard */}
        {hoveredSite && (
          <div
            style={{
              position: 'absolute',
              top: 10,
              right: 10,
              background: '#0C1524',
              border: '1px solid #1F2E45',
              borderRadius: 8,
              padding: '8px 12px',
              fontSize: '0.75rem',
              color: '#DCE6F2',
              boxShadow: '0 6px 20px rgba(0,0,0,0.5)',
              zIndex: 10,
              fontFamily: 'Barlow, sans-serif',
            }}
          >
            <div style={{ fontWeight: 700, fontSize: '0.85rem', color: '#F8FAFC' }}>{hoveredSite.name}</div>
            <div style={{ color: '#8597AE', fontSize: '0.72rem', fontFamily: 'JetBrains Mono' }}>IP: {hoveredSite.ip}</div>
            <div style={{ marginTop: 4, display: 'flex', gap: '0.5rem', fontSize: '0.72rem' }}>
              <span>Nodes: <strong>{hoveredSite.nodes}</strong></span>
              <span>Status: <strong style={{ color: isAnomalous && hoveredSite.id === 'frankfurt' ? '#F05A5A' : '#2ECC8F' }}>{isAnomalous && hoveredSite.id === 'frankfurt' ? 'Degraded' : 'Nominal'}</strong></span>
            </div>
          </div>
        )}
      </div>

      {/* Map Legend */}
      <div style={{ display: 'flex', gap: '1rem', flexWrap: 'wrap', color: '#8597AE', fontSize: '0.72rem', marginTop: '0.75rem', fontFamily: 'Barlow, sans-serif' }}>
        <span style={{ display: 'flex', alignItems: 'center', gap: 5 }}>
          <span style={{ width: 8, height: 8, borderRadius: '50%', background: '#2ECC8F' }} /> Healthy
        </span>
        <span style={{ display: 'flex', alignItems: 'center', gap: 5 }}>
          <span style={{ width: 8, height: 8, borderRadius: '50%', background: '#F0A93B' }} /> Degraded SLA
        </span>
        <span style={{ display: 'flex', alignItems: 'center', gap: 5 }}>
          <span style={{ width: 8, height: 8, borderRadius: '50%', background: '#F05A5A' }} /> Failing Link
        </span>
        <span style={{ display: 'flex', alignItems: 'center', gap: 5 }}>
          <span style={{ width: 8, height: 8, borderRadius: '50%', background: '#22C3E6' }} /> Rerouted / Healing
        </span>
      </div>
    </div>
  );
}
